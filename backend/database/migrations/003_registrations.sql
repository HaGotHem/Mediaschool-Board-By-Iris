-- 3. Visiteurs -----------------------------------------------------------
CREATE TABLE visitors (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    last_name varchar(100) NOT NULL,
    first_name varchar(100) NOT NULL,
    birth_date date NOT NULL,
    phone varchar(30) NOT NULL,
    email varchar(254) NOT NULL UNIQUE
);

-- 4. Inscriptions --------------------------------------------------------
CREATE TABLE registrations (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    visitor_id integer NOT NULL REFERENCES visitors(id),
    event_id integer NOT NULL REFERENCES events(id),
    current_class_id integer REFERENCES current_classes(id),
    school_id integer NOT NULL REFERENCES schools(id),
    entry_level_id integer NOT NULL REFERENCES entry_levels(id),
    specialty_id integer REFERENCES specialties(id),
    remark text,
    appointment_date date NOT NULL,
    time_slot_id integer NOT NULL REFERENCES time_slots(id),
    advisor_id integer NOT NULL REFERENCES advisors(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    -- Un conseiller ne peut avoir qu'un visiteur par créneau et par jour
    CONSTRAINT registrations_slot_uq UNIQUE (appointment_date, time_slot_id, advisor_id),
    -- Un visiteur ne s'inscrit qu'une fois par événement
    CONSTRAINT registrations_visitor_event_uq UNIQUE (visitor_id, event_id)
);

CREATE INDEX registrations_event_idx ON registrations (event_id);
CREATE INDEX registrations_school_idx ON registrations (school_id);

-- 5. Vue : créneaux encore disponibles le jour de chaque événement -------
CREATE VIEW available_slots AS
SELECT e.id AS event_id,
       e.event_date AS appointment_date,
       ts.id AS time_slot_id,
       ts.label AS time_slot_label,
       a.id AS advisor_id,
       a.label AS advisor_label
FROM events e
CROSS JOIN time_slots ts
CROSS JOIN advisors a
WHERE NOT EXISTS (
    SELECT 1 FROM registrations r
    WHERE r.appointment_date = e.event_date
      AND r.time_slot_id = ts.id
      AND r.advisor_id = a.id
)
ORDER BY ts.start_time, a.id;
-- 2. Créneaux horaires (rendez-vous d'1 h : 9h-12h puis 14h-16h) ---------
CREATE TABLE time_slots (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label varchar(30) NOT NULL,
    start_time time NOT NULL UNIQUE,
    end_time time NOT NULL,
    CONSTRAINT time_slots_order CHECK (end_time > start_time),
    CONSTRAINT time_slots_hours CHECK (
        (start_time >= '09:00' AND end_time <= '12:00')
        OR (start_time >= '14:00' AND end_time <= '16:00')
    )
);

